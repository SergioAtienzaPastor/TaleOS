    private static volatile String language = DEFAULT_LANGUAGE;
    private static final Map<String, String> SPANISH = createSpanish();
    private static final Map<String, String> LEGACY_ENGLISH = createLegacyEnglish();
    private static final Map<String, String> LEGACY_PARTS = createLegacyParts();

    private I18n() {
    }

    public static void setLanguage(String value) {
        language = "es".equalsIgnoreCase(value) ? "es" : DEFAULT_LANGUAGE;
    }

    public static String language() {
        return language;
    }

    public static String t(String text) {
        if (text == null) {
            return null;
        }
        if (language.equals("es")) {
            return SPANISH.getOrDefault(text, text);
        }
        String translated = LEGACY_ENGLISH.getOrDefault(text, text);
        for (Map.Entry<String, String> entry : LEGACY_PARTS.entrySet()) {
            translated = translated.replace(entry.getKey(), entry.getValue());
        }
        return translated;
    }

